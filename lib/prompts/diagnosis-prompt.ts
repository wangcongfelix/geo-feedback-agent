/**
 * 将用户本次提交的信息转换成模型可以读取的内容。
 *
 * JSON.stringify能够保留字段结构，
 * 比直接拼接一大段自然语言更稳定，也更容易调试。
 */
export function buildDiagnosisUserPrompt(
  input: FeedbackInput
): string {
  return [
    '请诊断以下一条用户反馈。',
    '输入JSON中的空字符串表示用户没有提供该信息。',
    '只能基于以下内容进行判断：',
    JSON.stringify(input, null, 2)
  ].join('\n\n')
}